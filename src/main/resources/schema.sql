CREATE TABLE IF NOT EXISTS users(--もし存在しないならusers表を作成してね
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,--GENERATED～IDENTITY＝IDをポスグレが自動生成
	name VARCHAR(50) NOT NULL,
	email VARCHAR(100) NOT NULL UNIQUE,--UNIQUE→メアドの重複を拒否
	password VARCHAR(100) NOT NULL,
	role VARCHAR(20) NOT NULL DEFAULT 'ROLE_USER',--権限　デフォだと'ROLE_USER'ですよ
	created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP--登録日時取得
		--DEFAULTはINSERTの際に記述がなくても自動的にデフォが設定される
);

CREATE TABLE IF NOT EXISTS categories (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS products (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	category_id INT NOT NULL REFERENCES categories(id),--references=参照　カテゴリ表id→外部キーに指定
	name VARCHAR(100) NOT NULL,
	description TEXT, --商品の説明。NOTNULLが無いので空文字も許可
	price INT NOT NULL,
	stock INT NOT NULL DEFAULT 0,
	image_path VARCHAR(200),--商品イメージ画像の場所=パスを指定(/images/products/keyboard.jpgとか)
	deleted_flag BOOLEAN NOT NULL DEFAULT FALSE,
	--DELETE文だと商品データ自体消える。　"論理削除"により商品一覧には表示しないよう設定
	created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP--デフォで現在時刻が入る
);

CREATE TABLE IF NOT EXISTS orders (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id INT NOT NULL REFERENCES users(id),
	total_price INT NOT NULL,
	status VARCHAR(20) NOT NULL DEFAULT 'PAID',
	ordered_at TIMESTAMP NOT NULL DEFAULT  CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS order_items (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	order_id INT NOT NULL REFERENCES orders(id),
	product_id INT NOT NULL REFERENCES products(id),
	product_name VARCHAR(100) NOT NULL,
	unit_price INT NOT NULL,
	quantity INT NOT NULL
);
